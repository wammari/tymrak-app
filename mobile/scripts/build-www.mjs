// Builds mobile/www: the employee pages of the web app, packaged for the iPhone/Android app.
// The pages are copied unchanged except for one added line that loads native-config.js
// (which points "/api/..." at the live server) right before api-base.js. Run from mobile/:
//   npm run build        (then `npx cap sync` copies www into the iOS and Android projects)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "../..");
const out = path.resolve(here, "../www");
export const API_BASE = process.env.TYMRAK_API_BASE || "https://app.tymrak.com";

// Everything an employee uses: sign in, password help, clock, timecard, time off, business
// switcher, account deletion. Manager pages stay on the web portal for now.
export const PAGES = ["login.html", "password-recovery.html", "reset-password.html", "employee.html", "timecard.html"];
export const FILES = [
  "tymrak-theme.css", "api-base.js", "password-toggle.js", "support.js", "supabase-config.js", "supabase-js.bundle.js",
  "account-deletion-ui.js", "employee-business.js", "geolocation.js", "punch-client.js", "pay-periods.js",
  "timecard-calculation.js", "tymrak-logo.png"
];

export function nativeConfig(base = API_BASE) {
  if (!/^https:\/\/[a-z0-9.-]+$/i.test(base)) throw new Error(`TYMRAK_API_BASE must be an https origin, got ${base}`);
  return `// Generated by mobile/scripts/build-www.mjs for the app build only.\nwindow.TYMRAK_API_BASE = ${JSON.stringify(base)};\nwindow.TYMRAK_NATIVE_APP = true;\n`;
}

export function addNativeConfig(html, page) {
  const tag = '<script src="/api-base.js"></script>';
  if (!html.includes(tag)) throw new Error(`${page} doesn't load /api-base.js the expected way`);
  return html.replace(tag, `<script src="/native-config.js"></script>\n${tag}`);
}

// Pages that only exist on the website (privacy policy, terms) open on app.tymrak.com.
export function webOnlyLinks(script, base = API_BASE) {
  return script.replace(/(["'])\/(privacy|terms)\1/g, (_, quote, page) => `${quote}${base}/${page}${quote}`);
}

// The app opens on index.html: straight to the clock if signed in, otherwise to sign-in.
export const START_PAGE = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>TYMRAK</title><style>body{margin:0;background:#fff9f0}</style></head><body>
<script>
(function(){
  var signedIn=false;
  try{for(var i=0;i<localStorage.length;i++){var key=localStorage.key(i);if(/^sb-.*-auth-token$/.test(key)&&localStorage.getItem(key)){signedIn=true;break}}}catch(e){}
  location.replace(signedIn?"/employee.html":"/login.html");
})();
</script></body></html>
`;

export function build() {
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  for (const page of PAGES) {
    fs.writeFileSync(path.join(out, page), addNativeConfig(fs.readFileSync(path.join(appRoot, page), "utf8"), page));
  }
  for (const file of FILES) {
    const source = path.join(appRoot, file);
    if (file === "support.js") fs.writeFileSync(path.join(out, file), webOnlyLinks(fs.readFileSync(source, "utf8")));
    else fs.copyFileSync(source, path.join(out, file));
  }
  fs.writeFileSync(path.join(out, "native-config.js"), nativeConfig());
  fs.writeFileSync(path.join(out, "index.html"), START_PAGE);
  console.log(`Built ${out} (${PAGES.length} pages, API ${API_BASE})`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) build();
